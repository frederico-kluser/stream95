// commitlint configuration for stream95.
//
// Enforces Conventional Commits (https://www.conventionalcommits.org/).
// Wired to the `commit-msg` git hook via husky (`npm install` runs `prepare`):
// invalid messages are rejected at commit time. The CI checks them again.
//
// Rules use the [level, applicable, value] form: 2 = error, 'always' = enforce.
export default {
  // Start from the community-standard preset: type-enum, type-empty,
  // subject-empty, header-max-length, body-leading-blank, ...
  extends: ['@commitlint/config-conventional'],

  rules: {
    // Only these types are allowed. They map 1:1 to the changelog sections
    // generated by git-cliff (cliff.toml) and to the release notes.
    'type-enum': [
      2,
      'always',
      ['feat', 'fix', 'docs', 'style', 'refactor', 'perf', 'test', 'build', 'ci', 'chore', 'revert'],
    ],

    // Subject must be sentence-case ("Add retry logic") or lower-case
    // ("add retry logic"); no SHOUTING or random casing.
    'subject-case': [2, 'always', ['sentence-case', 'lower-case']],

    // Keep the commit header short enough for git log --oneline, GitHub UI,
    // and release notes. Use the body for details; put breaking changes in the
    // `BREAKING CHANGE:` footer.
    'header-max-length': [2, 'always', 72],
  },
};
